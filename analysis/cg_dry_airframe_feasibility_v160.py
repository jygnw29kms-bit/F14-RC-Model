import json, pathlib
root=pathlib.Path(r"C:\Users\dezen\Desktop\F14-RC-Model")
v151=json.loads((root/'analysis/cg_whole_aircraft_sensitivity_v151.json').read_text())
v152=json.loads((root/'analysis/cg_battery_tray_v152.json').read_text())
# Battery center positions proven by v157.
bx=[305.0,340.0,375.0]
# Use the broad preliminary seed range, not a frozen CG.
seeds=v151['preliminary_maiden_CG_seeds_from_forwardmost_NP']
targets=sorted(float(v) for v in seeds.values())
target_min=min(targets); target_max=max(targets)
# Representative AUW and battery mass sensitivity from existing requirements.
auws=[950,1050,1100,1200]
batts=[180,202,220,240]
rows=[]
for auw in auws:
  for mb in batts:
    if mb>=auw: continue
    dry=auw-mb
    # Required dry CG when battery is at each extreme and target at each extreme.
    vals=[]
    for target in [target_min,target_max]:
      for xb in [bx[0],bx[-1]]:
        xdry=(target*auw-mb*xb)/dry
        vals.append({'target_cg_mm':target,'battery_x_mm':xb,'required_dry_cg_mm':xdry})
    # For a given dry CG, reachable aircraft CG interval is generated by battery travel.
    # Dry-CG acceptance interval that allows at least one combination to hit any target in target range:
    possible_min=min(v['required_dry_cg_mm'] for v in vals)
    possible_max=max(v['required_dry_cg_mm'] for v in vals)
    # To guarantee the full target range can be reached with battery travel, dry CG must satisfy
    # target_min reachable at one battery extreme AND target_max at the other.
    # Since moving battery aft moves total CG aft:
    lower=(target_max*auw-mb*bx[-1])/dry
    upper=(target_min*auw-mb*bx[0])/dry
    full_range_possible=lower<=upper
    rows.append({'AUW_g':auw,'battery_g':mb,'dry_airframe_g':dry,'dry_cg_interval_for_any_seed_mm':[possible_min,possible_max],'dry_cg_interval_to_cover_entire_seed_range_mm':[lower,upper] if full_range_possible else None,'full_seed_range_coverable_by_70mm_battery_travel':full_range_possible,'detail':vals})
ref=next(x for x in rows if x['AUW_g']==1050 and x['battery_g']==202)
result={
 'status':'V160_BATTERY_TRAVEL_DRY_AIRFRAME_CG_FEASIBILITY',
 'sources':['analysis/cg_whole_aircraft_sensitivity_v151.json','analysis/cg_battery_tray_v152.json','workspace/RC-F14-Tomcat/Fusion/Exports/Current/cg_v157/F14_v157_battery_skeleton_tray_audit.json'],
 'preliminary_CG_seed_range_mm':[target_min,target_max],
 'battery_center_proven_range_mm':[bx[0],bx[-1]],
 'battery_travel_mm':bx[-1]-bx[0],
 'cases':rows,
 'reference_1050g_202g':ref,
 'decision':{
   'reference_case_full_seed_range_coverable':ref['full_seed_range_coverable_by_70mm_battery_travel'],
   'required_reference_dry_airframe_CG_interval_mm':ref['dry_cg_interval_to_cover_entire_seed_range_mm'],
   'next_physical_mass_gate':'With battery removed, weigh the assembled dry airframe and measure its CG. If its CG is outside the applicable interval, move equipment before adding ballast.',
   'ballast_is_not_accepted_as_primary_design_solution':True,
   'do_not_freeze_maiden_CG_from_this_screen':True
 },
 'release':{'dry_airframe_mass_measured':False,'dry_airframe_CG_measured':False,'maiden_CG_frozen':False,'flight_release':False}
}
(root/'analysis/cg_dry_airframe_feasibility_v160.json').write_text(json.dumps(result,indent=2),encoding='utf-8')
print(json.dumps({'seed_range':[target_min,target_max],'ref':ref,'decision':result['decision']},indent=2))